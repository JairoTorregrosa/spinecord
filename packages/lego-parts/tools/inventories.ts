// Writes data/sets.json: the complete part inventories of the three EV3 sets, from Rebrickable's CSV downloads
// (https://rebrickable.com/downloads/). Download sets, inventories, inventory_parts, parts and colors (.csv.gz)
// into one folder, then (cross-platform):
//   bun packages/lego-parts/tools/inventories.ts --csv <folder>
// The newest inventory version of each set is used.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { LegoSet, SetLine } from "../types.ts";

const SETS = ["31313-1", "45544-1", "45560-1"];
const CDN = "https://cdn.rebrickable.com/media/downloads/";
const argv = process.argv.slice(2);
const dir = argv.includes("--csv") ? argv[argv.indexOf("--csv") + 1] : undefined;
if (!dir || !existsSync(dir)) throw new Error("--csv <folder> must name a folder with Rebrickable's .csv.gz downloads");

/** RFC 4180 rows; Rebrickable quotes fields that hold commas. `keep` sees each line's first field before the line is
 * parsed, so the 130 MB inventory_parts file is filtered without building its rows. */
function csv(name: string, keep?: (first: string) => boolean): Record<string, string>[] {
  const path = join(dir!, `${name}.csv.gz`);
  if (!existsSync(path)) throw new Error(`missing ${path} (download ${CDN}${name}.csv.gz)`);
  let text = new TextDecoder().decode(Bun.gunzipSync(readFileSync(path)));
  if (keep) {
    const lines = text.split("\n");
    text = [lines[0], ...lines.slice(1).filter((l) => keep(l.slice(0, l.indexOf(","))))].join("\n");
  }
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i]!;
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field || row.length) rows.push([...row, field]);
  const [head, ...body] = rows;
  if (!head) throw new Error(`${path} is empty`);
  return body.filter((r) => r.length === head.length).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]!])));
}

const sets = new Map(csv("sets").map((s) => [s.set_num!, s]));
const colours = new Map(csv("colors").map((c) => [c.id!, c.name!]));
const inventories = csv("inventories").filter((i) => SETS.includes(i.set_num!));
const latest = new Map<string, { id: string; version: number }>();
for (const i of inventories) {
  const v = Number(i.version);
  if ((latest.get(i.set_num!)?.version ?? -1) < v) latest.set(i.set_num!, { id: i.id!, version: v });
}
const byInventory = new Map<string, SetLine[]>();
const wanted = new Set([...latest.values()].map((l) => l.id));
for (const p of csv("inventory_parts", (id) => wanted.has(id))) {
  const colour = colours.get(p.color_id!);
  if (colour === undefined) throw new Error(`unknown colour ${p.color_id}`);
  const line: SetLine = {
    part: p.part_num!,
    colour_id: Number(p.color_id),
    colour,
    quantity: Number(p.quantity),
    spare: p.is_spare === "True",
  };
  byInventory.set(p.inventory_id!, [...(byInventory.get(p.inventory_id!) ?? []), line]);
}
const out: LegoSet[] = SETS.map((num) => {
  const s = sets.get(num);
  const inv = latest.get(num);
  if (!s || !inv) throw new Error(`Rebrickable has no set or inventory for ${num}`);
  const lines = (byInventory.get(inv.id) ?? []).sort(
    (a, b) => a.part.localeCompare(b.part) || a.colour_id - b.colour_id || Number(a.spare) - Number(b.spare),
  );
  return {
    set: num,
    name: s.name!,
    year: Number(s.year),
    source: `https://rebrickable.com/sets/${num}/`,
    inventory_source: `${CDN}inventory_parts.csv.gz`,
    inventory_version: inv.version,
    lines,
  };
});
const partNames = new Map(csv("parts").map((p) => [p.part_num!, p.name!]));
const names = Object.fromEntries(
  [...new Set(out.flatMap((s) => s.lines.map((l) => l.part)))].sort().map((p) => [p, partNames.get(p) ?? "?"]),
);
writeFileSync(
  join(import.meta.dir, "..", "data", "sets.json"),
  `${JSON.stringify({ note: "Generated by tools/inventories.ts from Rebrickable's CSV downloads; do not edit. Part numbers are Rebrickable's.", fetched: new Date().toISOString().slice(0, 10), sets: out, part_names: names }, null, 2)}\n`,
);
console.log(out.map((s) => `${s.set} v${s.inventory_version}: ${s.lines.length} lines`).join("\n"));
